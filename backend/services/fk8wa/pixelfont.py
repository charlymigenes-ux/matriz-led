"""Fuentes de píxeles del panel FK-8Wa, definidas en código.

Sin archivos TTF: el resultado es idéntico en cualquier sistema operativo y
no depende de licencias de fuentes (Consolas, la fuente con la que se diseñó
la vista previa original, es de Microsoft y no se puede distribuir).

Tres tamaños:
- BIG   6x11, trazo doble: NOPAL, P1, "3 IDLE", PAUSA, porcentajes.
- SMALL 5x7: textos normales; caben dos renglones en las 16 filas.
- TINY  3x5: respaldo cuando un texto no cabe en SMALL.

Las minúsculas se dibujan en mayúsculas y los acentos se quitan (salvo la Ñ).
Un carácter sin glifo se dibuja como "?" y se registra una sola vez.
"""

from __future__ import annotations

import logging
import unicodedata
from typing import Dict, List

from PIL import Image

logger = logging.getLogger(__name__)
_missing_logged = set()


class Font:
    def __init__(self, name: str, height: int, glyphs: Dict[str, List[str]], space: int, spacing: int = 1):
        self.name, self.height, self.spacing = name, height, spacing
        self.glyphs = dict(glyphs)
        self.glyphs[" "] = ["." * space] * height
        for ch, rows in self.glyphs.items():
            if len(rows) != height or len({len(r) for r in rows}) != 1:
                raise ValueError(f"glifo mal formado en {name}: {ch!r}")

    def has(self, ch: str) -> bool:
        return ch in self.glyphs

    def glyph(self, ch: str) -> List[str]:
        if ch in self.glyphs:
            return self.glyphs[ch]
        key = (self.name, ch)
        if key not in _missing_logged:
            _missing_logged.add(key)
            logger.warning(f"Panel FK-8Wa: la fuente {self.name} no tiene el carácter {ch!r}; se muestra '?'")
        return self.glyphs["?"]


def normalize(text: str) -> str:
    """Mayúsculas y sin acentos, conservando la Ñ."""
    out = []
    for ch in str(text).upper():
        if ch == "Ñ":
            out.append(ch)
            continue
        base = unicodedata.normalize("NFD", ch)[0]
        out.append(base)
    return "".join(out)


def text_width(text: str, font: Font) -> int:
    text = normalize(text)
    if not text:
        return 0
    return sum(len(font.glyph(ch)[0]) for ch in text) + font.spacing * (len(text) - 1)


def fits(text: str, font: Font) -> bool:
    """True si todos los caracteres existen en la fuente (sin reemplazar por '?')."""
    return all(font.has(ch) for ch in normalize(text))


def draw_text(img: Image.Image, x: int, y: int, text: str, font: Font) -> int:
    """Dibuja `text` con su esquina superior izquierda en (x, y). Recorta en los
    bordes de la imagen. Devuelve la x siguiente al último glifo."""
    px = img.load()
    w, h = img.size
    for ch in normalize(text):
        rows = font.glyph(ch)
        for j, row in enumerate(rows):
            for i, c in enumerate(row):
                if c == "#" and 0 <= x + i < w and 0 <= y + j < h:
                    px[x + i, y + j] = 1
        x += len(rows[0]) + font.spacing
    return x - font.spacing


def _g(*rows: str) -> List[str]:
    return list(rows)


